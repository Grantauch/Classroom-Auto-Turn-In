const fs=require('fs'),path=require('path'),assert=require('assert');
const root=path.join(__dirname,'..');
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
const win=pkg.build?.win||{};
assert(!Object.prototype.hasOwnProperty.call(win,'signExecutable'),'Pinned electron-builder 26.0.12 rejects win.signExecutable.');
assert.equal(win.signAndEditExecutable,false,'Restricted-PC recovery build must bypass electron-builder winCodeSign resource/sign helper.');
assert.equal(pkg.build?.afterPack,'./scripts/after-pack-windows.js');
assert.equal(pkg.build?.nsis?.oneClick,true,'Teacher installer must be forced current-user one-click; assisted mode exposes per-machine choice.');
assert.equal(pkg.build?.nsis?.perMachine,false,'Teacher installer must be current-user only.');
assert.equal(pkg.build?.nsis?.packElevateHelper,false,'Current-user teacher installer must not pack the elevation helper.');
assert.equal(pkg.build?.nsis?.runAfterFinish,false,'Builder validation must control when the installed app launches.');
assert.equal(pkg.devDependencies?.resedit,'1.7.2');
const hook=fs.readFileSync(path.join(root,'scripts','after-pack-windows.js'),'utf8');
assert(hook.includes("require('resedit')"));
assert(hook.includes('ignoreCert: true'),'Electron Windows binaries can be signed upstream; resedit must parse them with ignoreCert.');
assert(hook.includes('replaceIconsForResource'));
assert(hook.includes('setFileVersion'));
assert(hook.includes('setProductVersion'));
assert(hook.includes('VersionInfo.fromEntries'));
const validation=fs.readFileSync(path.join(root,'scripts','windows-installed-validation.ps1'),'utf8');
assert(validation.includes('ProductName')&&validation.includes('FileDescription')&&validation.includes('FileVersion'),'Installed validation must verify resource metadata.');
assert(validation.includes('--self-test-user-data=')&&validation.includes('--self-test-browser'),'Installed validation must isolate userData and run the packaged browser engine.');
assert(validation.includes('Validation refused to run because a real Classroom Auto Turn-In scheduled task already exists'),'Installed validation must refuse to touch production CATI tasks.');
assert(!validation.includes('Register-ScheduledTask'),'Installed validation must not seed real scheduled tasks.');
assert(validation.includes('already installed at $existingApp'),'Installed validation must refuse to overwrite a real CATI installation.');
assert(validation.includes('$maxAttempts=4')&&validation.includes('$p.ExitCode -ne -1073741819')&&validation.includes('partial application executable'),'Installed validation may retry only the known pre-install NSIS access-violation flake and must still fail closed on partial installs.');
const bat=fs.readFileSync(path.join(root,'BUILD-SETUP-EXE.bat'),'utf8');
assert(bat.includes('CSC_IDENTITY_AUTO_DISCOVERY=false'));
assert(bat.includes('WIN_CSC_LINK='));
console.log('Windows build configuration regression checks passed.');
